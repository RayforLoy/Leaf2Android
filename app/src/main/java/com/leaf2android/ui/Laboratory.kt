@Composable
internal fun LaboratoryDialog(repo: LeafRepository, shareFile: (File) -> Unit, close: () -> Unit) {
    val state by repo.state.collectAsStateWithLifecycle()
    val settings by repo.settings.collectAsStateWithLifecycle()
    val context = LocalContext.current
    val research = remember { FirmwareLabTemplates.load(context) }
    val chinese = L10n.isChinese
    var selection by rememberSaveable { mutableStateOf("custom") }
    var inputs by rememberSaveable { mutableStateOf(emptyMap<String, String>()) }
    var raw by rememberSaveable { mutableStateOf("") }
    var generated by rememberSaveable { mutableStateOf("") }
    var expected by rememberSaveable { mutableStateOf("Ack") }
    var expectedFile by rememberSaveable { mutableStateOf("") }
    var attachment by rememberSaveable { mutableStateOf(false) }
    var seconds by rememberSaveable { mutableStateOf("20") }
    var error by rememberSaveable { mutableStateOf<String?>(null) }
    var confirm by rememberSaveable { mutableStateOf(false) }
    var acknowledgeErase by rememberSaveable { mutableStateOf(false) }
    var expandedId by rememberSaveable { mutableStateOf<String?>(null) }
    val selectedResearch = research.firstOrNull { selection == "research:${it.id}" }
    val template = LabExperiments.templates.firstOrNull { it.id == selection } ?: selectedResearch?.template
    val timeout = seconds.toLongOrNull()?.takeIf { it in 1..300 }?.times(1000)
    val labels = linkedMapOf("custom" to tr(R.string.lab_custom_command)).apply {
        LabExperiments.templates.forEach { put(it.id, if (chinese) it.titleZh else it.titleEn) }
        research.forEach { put("research:${it.id}", if (chinese) it.titleZh else it.titleEn) }
    }
    val encoded = runCatching { LabExperiments.command(raw, settings.encoding, expected, expectedFile.takeIf(String::isNotBlank), attachment, timeout ?: 0) }
    val command = encoded.getOrNull()
    val erases = runCatching { command?.let { HeaderParser.parse(it.bytes(settings.encoding)) }?.let { it.tag.equals("FileCommand",true) && it.value("FileCommand").equals("qformat",true) } }.getOrDefault(false) == true
    LaunchedEffect(Unit) { repo.enterLaboratory() }
    LaunchedEffect(state.labRecords.firstOrNull()?.id) { expandedId = state.labRecords.firstOrNull()?.id }
    fun finish() { repo.leaveLaboratory(); close() }
    fun showFailure(e: Throwable) { error = if (e is ProtocolException) e.messageForLanguage(chinese) else e.message }
    fun build() {
        try {
            val t = template ?: throw ProtocolException("请手填命令或选择已知模板", "Enter a command or select a known template.")
            val built = if (t.id.startsWith("firmware-")) FirmwareLabTemplates.build(t, inputs, settings.encoding, t.defaultExpectedTag)
                else LabExperiments.build(t.id, inputs, settings.encoding)
            raw = built.text; generated = raw; expected = built.responseTag
            val parsed = HeaderParser.parse(built.bytes(settings.encoding))
            expectedFile = parsed.value("file_name", settings.encoding.charset).orEmpty()
            attachment = parsed.tag.equals("GetImage", true) && expected !in setOf("", "*"); error = null
        } catch (e: Exception) { showFailure(e) }
    }

    Dialog(onDismissRequest = ::finish, properties = DialogProperties(usePlatformDefaultWidth = false, decorFitsSystemWindows = false)) {
        Surface(Modifier.fillMaxSize()) {
            Column(Modifier.fillMaxSize().systemBarsPadding().imePadding()) {
                Row(Modifier.fillMaxWidth().padding(horizontal = 10.dp), verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
                    IconButton(onClick = ::finish) { Icon(Icons.Default.ArrowBack, tr(R.string.lab_finish)) }
                    Text(tr(R.string.laboratory), Modifier.weight(1f), style = MaterialTheme.typography.titleLarge)
                    TextButton(onClick = { repo.exportLaboratory(shareFile) }, enabled = state.labRecords.isNotEmpty() && !state.labBusy) { Text(tr(R.string.lab_export)) }
                }
                Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(horizontal = 20.dp), verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    Text(state.deviceName + " · " + state.phase.label, style = MaterialTheme.typography.titleSmall)
                    Text(tr(R.string.lab_intro), style = MaterialTheme.typography.bodySmall)
                    Text(tr(R.string.lab_exit_behavior), style = MaterialTheme.typography.bodySmall)
                    Text(tr(R.string.lab_limit_info, settings.attachmentLimitMiB), style = MaterialTheme.typography.bodySmall)
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        listOf(16,64).forEach { size -> FilterChip(settings.attachmentLimitMiB == size,
                            { repo.updateSettings { it.copy(attachmentLimitMiB = size) } }, enabled = !state.active,
                            label = { Text("$size MiB") }) }
                    }
                    ControlChoice(tr(R.string.lab_template), labels[selection] ?: labels.getValue("custom"), labels.values.toList(), !state.labBusy, "lab-template") { chosen ->
                        selection = labels.entries.first { it.value == chosen }.key; inputs = emptyMap(); raw = ""; generated = ""; expectedFile = ""; attachment = false; error = null
                        expected = LabExperiments.templates.firstOrNull { it.id == selection }?.defaultExpectedTag ?: research.firstOrNull { selection == "research:${it.id}" }?.template?.defaultExpectedTag ?: "Ack"
                    }
                    template?.let { t ->
                        Text(if (chinese) t.notesZh else t.notesEn, style = MaterialTheme.typography.bodySmall)
                        Text(tr(R.string.lab_evidence) + "\n" + t.provenance, style = MaterialTheme.typography.labelSmall)
                        Text(t.impacts.joinToString(" · ") { if (chinese) it.titleZh else it.titleEn }, style = MaterialTheme.typography.labelMedium, color = MaterialTheme.colorScheme.primary)
                        t.requiresInputs.forEach { input ->
                            OutlinedTextField(inputs[input.id].orEmpty(), { inputs = inputs + (input.id to it) },
                                label = { Text(if (chinese) input.titleZh else input.titleEn) },
                                visualTransformation = if (input.secret) PasswordVisualTransformation() else VisualTransformation.None,
                                minLines = if (input.kind == LabInputKind.BASE64_XMP) 2 else 1, maxLines = 4, modifier = Modifier.fillMaxWidth(), enabled = !state.labBusy)
                            val format = if (chinese) input.formatZh else input.formatEn
                            if (format.isNotBlank()) Text(format, style = MaterialTheme.typography.bodySmall)
                            if (input.suggestions.isNotEmpty()) Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                input.suggestions.forEach { value -> SuggestionChip(onClick = { inputs = inputs + (input.id to value) }, label = { Text(value) }, enabled = !state.labBusy) }
                            }
                        }
                        if (t.requiresInputs.any { it.id in setOf("fileName", "photo_path") }) TextButton(onClick = {
                            state.selected?.let { photo -> inputs = inputs + ((if (t.requiresInputs.any { it.id == "fileName" }) "fileName" else "photo_path") to photo.path) }
                        }, enabled = state.selected != null && !state.labBusy) { Text(tr(R.string.lab_use_selected_path)) }
                        if (t.requiresInputs.any { it.id == "xmp" }) TextButton(onClick = {
                            state.selected?.metadata?.entries?.firstOrNull { it.key.equals("xmp_tag", true) }?.value?.let { inputs = inputs + ("xmp" to it) }
                        }, enabled = state.selected?.metadata?.keys?.any { it.equals("xmp_tag", true) } == true && !state.labBusy) { Text(tr(R.string.lab_use_selected_xmp)) }
                        OutlinedButton(onClick = ::build, enabled = !state.labBusy) { Text(tr(R.string.lab_generate)) }
                    }
                    selectedResearch?.takeIf { it.template == null }?.let { item ->
                        Text(if (chinese) item.notesZh else item.notesEn, style = MaterialTheme.typography.bodySmall)
                        Text("${item.level}\n${item.evidence}", style = MaterialTheme.typography.labelSmall)
                        item.hypothesis?.let { header ->
                            Text(tr(R.string.lab_hypothesis_notice), style = MaterialTheme.typography.bodySmall)
                            OutlinedButton(onClick = { raw = header; generated = ""; expected = "*"; expectedFile = ""; attachment = false; error = null }, enabled = !state.labBusy) { Text(tr(R.string.lab_make_hypothesis)) }
                        }
                    }
                    OutlinedTextField(raw, { raw = it }, label = { Text(tr(R.string.lab_raw_header)) }, modifier = Modifier.fillMaxWidth().testTag("lab-raw-command"),
                        minLines = 3, maxLines = 8, enabled = !state.labBusy, textStyle = MaterialTheme.typography.bodySmall.copy(fontFamily = FontFamily.Monospace))
                    OutlinedTextField(expected, { expected = it; if (it == "*" || it.isEmpty()) { expectedFile = ""; attachment = false } }, label = { Text(tr(R.string.lab_expected_tag)) }, modifier = Modifier.fillMaxWidth(), singleLine = true, enabled = !state.labBusy)
                    Text(tr(R.string.lab_matching_help), style = MaterialTheme.typography.bodySmall)
                    OutlinedTextField(expectedFile, { expectedFile = it }, label = { Text(tr(R.string.lab_expected_file)) }, modifier = Modifier.fillMaxWidth(), enabled = !state.labBusy && expected !in setOf("", "*"))
                    Row(verticalAlignment = androidx.compose.ui.Alignment.CenterVertically) {
                        Checkbox(attachment, { attachment = it }, enabled = !state.labBusy && expected !in setOf("", "*")); Text(tr(R.string.lab_require_attachment), style = MaterialTheme.typography.bodySmall)
                    }
                    OutlinedTextField(seconds, { seconds = it }, label = { Text(tr(R.string.lab_timeout)) }, modifier = Modifier.fillMaxWidth(), singleLine = true, enabled = !state.labBusy)
                    error?.let { Text(it, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }
                    if (raw.isNotEmpty() && command == null) Text(tr(R.string.lab_invalid_request), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.error)
                    state.error?.let { Text(it.resolve(), color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }
                    if (state.labBusy) {
                        LinearProgressIndicator(Modifier.fillMaxWidth())
                        if (state.expected > 0) Text("${state.received} / ${state.expected} bytes", style = MaterialTheme.typography.labelSmall)
                        OutlinedButton(onClick = repo::cancelLabExperiment) { Text(tr(R.string.lab_cancel_disconnect)) }
                    } else Button(onClick = { acknowledgeErase = false; confirm = true }, enabled = state.connected && command != null && timeout != null, modifier = Modifier.testTag("lab-review-send")) { Text(tr(R.string.lab_review_send)) }
                    Text(tr(R.string.lab_record_semantics), style = MaterialTheme.typography.bodySmall)
                    state.labRecords.forEach { record ->
                        OutlinedCard(onClick = { expandedId = if (expandedId == record.id) null else record.id }, modifier = Modifier.fillMaxWidth()) {
                            Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                                Text(record.time + " · " + tr(when (record.outcome) { LabOutcome.SENDING -> R.string.lab_sending; LabOutcome.RECEIVED -> R.string.lab_received; LabOutcome.SENT_ONLY -> R.string.lab_sent_only; LabOutcome.ERROR -> R.string.lab_error; LabOutcome.CANCELLED -> R.string.lab_cancelled }), style = MaterialTheme.typography.labelMedium)
                                Text(record.request.take(160), style = MaterialTheme.typography.bodySmall, fontFamily = FontFamily.Monospace)
                                if (expandedId == record.id) SelectionContainer { Column {
                                    Text(record.device, style = MaterialTheme.typography.labelSmall)
                                    record.response?.let { Text(it.take(4096), style = MaterialTheme.typography.bodySmall, fontFamily = FontFamily.Monospace) }
                                    record.responseErrorCode?.let { Text("error_code=$it", style = MaterialTheme.typography.labelMedium) }
                                    record.error?.let { Text(it, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }
                                    if (record.attachmentBytes > 0) {
                                        Text("${record.attachmentBytes} bytes\nSHA-256: ${record.attachmentSha256}", style = MaterialTheme.typography.labelSmall)
                                        Text(record.attachmentHex.orEmpty(), style = MaterialTheme.typography.labelSmall, fontFamily = FontFamily.Monospace)
                                    }
                                } }
                            }
                        }
                    }
                    if (state.labEvents.isNotEmpty()) {
                        Text(tr(R.string.lab_other_frames), style = MaterialTheme.typography.titleSmall)
                        SelectionContainer { Text(state.labEvents.takeLast(8).joinToString("\n\n") { it.take(4096) }, style = MaterialTheme.typography.labelSmall, fontFamily = FontFamily.Monospace) }
                    }
                    Spacer(Modifier.height(24.dp))
                }
            }
        }
    }
    if (confirm && command != null) AlertDialog(onDismissRequest = { confirm = false }, title = { Text(tr(R.string.lab_confirm_request)) }, text = {
        Column(Modifier.verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Text(state.deviceName, style = MaterialTheme.typography.titleSmall)
            Text(LabRedaction.redact(command.text), style = MaterialTheme.typography.bodySmall, fontFamily = FontFamily.Monospace)
            Text(tr(R.string.lab_record_semantics), style = MaterialTheme.typography.bodySmall)
            if (template?.writesBack == true || raw != generated) Text(tr(R.string.lab_write_effect), style = MaterialTheme.typography.bodySmall)
            if (erases) Row { Checkbox(acknowledgeErase, { acknowledgeErase = it }); Text(tr(R.string.lab_confirm_erase), style = MaterialTheme.typography.bodySmall) }
        }
    }, confirmButton = { TextButton(onClick = {
        val source = if (raw == generated) template?.id else if (selectedResearch?.hypothesis == raw) "user-hypothesis:${selectedResearch.id}" else null
        repo.runLabExperiment(raw, expected, expectedFile.takeIf(String::isNotBlank), attachment, timeout!!, source)
        confirm = false
        if (LabRedaction.redact(raw) != raw) { raw = ""; generated = ""; inputs = emptyMap() }
    }, enabled = state.connected && !state.labBusy && (!erases || acknowledgeErase), modifier = Modifier.testTag("lab-confirm-send")) { Text(tr(R.string.lab_send)) } }, dismissButton = { TextButton(onClick = { confirm = false }) { Text(tr(R.string.cancel_4d0b4)) } })
}
